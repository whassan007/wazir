#!/usr/bin/env node
// Renders the Homebrew formula, Scoop manifest and WinGet manifests for one release, with the
// exact SHA-256 values from that release's SHA256SUMS. Used by the manifest-update workflow
// after a release is published, and by CI to install from locally built artifacts.
//
//   node scripts/render-manifests.mjs --version 0.1.60 --sums release/SHA256SUMS
//        [--base-url https://github.com/whassan007/wazir/releases/download/v0.1.60] [--out .]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
const version = opt('--version');
if (!version || !/^\d+\.\d+\.\d+([-.][0-9A-Za-z.-]+)?$/.test(version)) throw new Error('--version <x.y.z> is required');
const repo = 'whassan007/wazir';
const baseUrl = opt('--base-url', `https://github.com/${repo}/releases/download/v${version}`).replace(/\/+$/, '');
const out = path.resolve(opt('--out', root));
const sums = Object.fromEntries(readFileSync(path.resolve(opt('--sums', 'SHA256SUMS')), 'utf8').split('\n').filter(Boolean)
  .map((l) => l.trim().split(/\s+\*?/)).map(([h, f]) => [f, h.toLowerCase()]));
const need = (file) => { const h = sums[file]; if (!/^[0-9a-f]{64}$/.test(h ?? '')) throw new Error(`${file} missing from SHA256SUMS`); return h; };
const pkg = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
const description = 'Model- and runtime-agnostic AI agent harness and control plane';
const write = (rel, text) => { const f = path.join(out, rel); mkdirSync(path.dirname(f), { recursive: true }); writeFileSync(f, text); console.log(rel); };

// ---- Homebrew: installs the npm tarball with Homebrew's Node -----------------------------
const tgz = `wazir-${version}.tgz`;
const rendered = [];
if (sums[tgz]) rendered.push('homebrew'), write('Formula/wazir.rb', `# Generated by scripts/render-manifests.mjs for v${version}; do not edit by hand.
class Wazir < Formula
  desc "${description}"
  homepage "https://github.com/${repo}"
  url "${baseUrl}/${tgz}"
  sha256 "${need(tgz)}"
  license "${pkg.license}"

  depends_on "node"

  def install
    # The npm package has no install scripts and never touches ~/.wazir; user state lives
    # outside the keg, so upgrades and uninstalls leave it in place.
    system "npm", "install", *std_npm_args
    bin.install_symlink libexec.glob("bin/*")
  end

  def caveats
    <<~EOS
      Wazir keeps its configuration and history in ~/.wazir (or $WAZIR_HOME).
      Uninstalling the formula does not remove it. Start with:
        wa doctor
    EOS
  end

  test do
    assert_equal "${version}", shell_output("#{bin}/wa --version").strip
    ENV["WAZIR_HOME"] = testpath/".wazir"
    assert_match "findings", shell_output("#{bin}/wa resources validate --json")
  end
end
`);

// ---- Scoop: the standalone wa.exe ---------------------------------------------------------
const winZip = (arch) => `wazir-${version}-windows-${arch}.zip`;
const scoopArch = {};
for (const [scoop, arch] of [['64bit', 'x64'], ['arm64', 'arm64']]) {
  if (sums[winZip(arch)]) scoopArch[scoop] = { url: `${baseUrl}/${winZip(arch)}`, hash: need(winZip(arch)) };
}
if (Object.keys(scoopArch).length) rendered.push('scoop', 'winget');
if (!rendered.length) throw new Error(`SHA256SUMS lists neither ${tgz} nor a Windows archive`);
if (Object.keys(scoopArch).length) write('packaging/scoop/wazir.json', `${JSON.stringify({
  version,
  description,
  homepage: `https://github.com/${repo}`,
  license: pkg.license,
  architecture: scoopArch,
  bin: 'wa.exe',
  notes: 'Wazir keeps its data in %USERPROFILE%\\.wazir; `scoop uninstall wazir` leaves it in place. Start with: wa doctor',
  checkver: { github: `https://github.com/${repo}` },
  autoupdate: { architecture: Object.fromEntries(Object.keys(scoopArch).map((k) => [k, { url: `https://github.com/${repo}/releases/download/v$version/wazir-$version-windows-${k === '64bit' ? 'x64' : 'arm64'}.zip`, hash: { url: `https://github.com/${repo}/releases/download/v$version/SHA256SUMS` } }])) },
}, null, 2)}\n`);

// ---- WinGet: zip with a nested portable executable ---------------------------------------
if (Object.keys(scoopArch).length) {
const id = 'whassan007.Wazir';
const dir = `packaging/winget/manifests/w/whassan007/Wazir/${version}`;
const header = (type) => `# yaml-language-server: $schema=https://aka.ms/winget-manifest.${type}.1.6.0.schema.json\n`;
write(`${dir}/${id}.yaml`, `${header('version')}PackageIdentifier: ${id}
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.6.0
`);
const installers = Object.entries(scoopArch).map(([k, v]) => `  - Architecture: ${k === '64bit' ? 'x64' : 'arm64'}
    InstallerUrl: ${v.url}
    InstallerSha256: ${v.hash.toUpperCase()}`).join('\n');
write(`${dir}/${id}.installer.yaml`, `${header('installer')}PackageIdentifier: ${id}
PackageVersion: ${version}
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: wa.exe
    PortableCommandAlias: wa
Commands:
  - wa
Installers:
${installers}
ManifestType: installer
ManifestVersion: 1.6.0
`);
write(`${dir}/${id}.locale.en-US.yaml`, `${header('defaultLocale')}PackageIdentifier: ${id}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: whassan007
PublisherUrl: https://github.com/whassan007
PackageName: Wazir
PackageUrl: https://github.com/${repo}
License: ${pkg.license}
LicenseUrl: https://github.com/${repo}/blob/v${version}/LICENSE
ShortDescription: ${description}
Moniker: wazir
Tags:
  - ai
  - agents
  - cli
ReleaseNotesUrl: https://github.com/${repo}/releases/tag/v${version}
ManifestType: defaultLocale
ManifestVersion: 1.6.0
`);
}
console.log(`rendered: ${rendered.join(', ')}`);
