import Foundation

enum PairingUriError: Error, LocalizedError {
    case empty
    case malformed(String)
    case wrongSchemeOrHost
    case containsPermanentToken
    case missingSessionOrSecret
    case insecureHttp(String)
    case missingHost
    case unsupportedScheme(String)

    var errorDescription: String? {
        switch self {
        case .empty: return "Pairing URI cannot be empty"
        case .malformed(let m): return "Malformed pairing URI: \(m)"
        case .wrongSchemeOrHost: return "Invalid pairing URI scheme or host; expected wazir://pair"
        case .containsPermanentToken: return "Pairing URI must not contain a permanent operator token"
        case .missingSessionOrSecret: return "Pairing URI is missing a valid sessionId or short-lived pairing secret"
        case .insecureHttp(let host): return "Insecure HTTP is not allowed for remote controllers (\(host)). Use HTTPS."
        case .missingHost: return "Controller URL must include a valid host"
        case .unsupportedScheme(let s): return "Unsupported URL scheme '\(s)'. Use https://"
        }
    }
}

/// Parses and validates a `wazir://pair?...` QR payload generated by `wa mobile pair`
/// (see `apps/api/src/mobile.ts` `MobilePairingService.createSession`). Mirrors the
/// Android `PairingUriParser` object field-for-field.
enum PairingUriParser {
    static func parse(_ rawUri: String) -> Result<ParsedPairingUri, Error> {
        let trimmed = rawUri.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return .failure(PairingUriError.empty) }

        guard let components = URLComponents(string: trimmed) else {
            return .failure(PairingUriError.malformed(trimmed))
        }
        guard (components.scheme?.lowercased() == "wazir"), (components.host?.lowercased() == "pair") else {
            return .failure(PairingUriError.wrongSchemeOrHost)
        }

        var params: [String: String] = [:]
        for item in components.queryItems ?? [] {
            params[item.name] = item.value ?? ""
        }

        if params["operatorToken"] != nil || params["token"] != nil || params["apiKey"] != nil {
            return .failure(PairingUriError.containsPermanentToken)
        }

        let sessionId = (params["sessionId"] ?? "").trimmingCharacters(in: .whitespaces)
        let secret = (params["secret"] ?? "").trimmingCharacters(in: .whitespaces)
        guard sessionId.count >= 6, secret.count >= 16 else {
            return .failure(PairingUriError.missingSessionOrSecret)
        }

        let name = params["name"]?.trimmingCharacters(in: .whitespaces).nilIfEmpty ?? "Wazir Controller"
        var validatedUrl: String?
        if let rawUrl = params["url"]?.trimmingCharacters(in: .whitespaces).nilIfEmpty {
            switch validateControllerBaseUrl(rawUrl, allowLoopbackHttp: true) {
            case .success(let url): validatedUrl = url
            case .failure(let err): return .failure(err)
            }
        }

        let fingerprint = params["fp"]?.trimmingCharacters(in: .whitespaces).nilIfEmpty
        let apiVersion = params["v"]?.trimmingCharacters(in: .whitespaces).nilIfEmpty ?? "1.0.0"

        return .success(ParsedPairingUri(
            sessionId: sessionId,
            pairingSecret: secret,
            controllerName: name,
            controllerUrl: validatedUrl,
            tlsCertFingerprint: fingerprint,
            apiVersion: apiVersion
        ))
    }

    /// Enforces HTTPS for remote controllers. Cleartext HTTP is only permitted for local
    /// loopback (127.0.0.1, localhost, ::1, or the Android-emulator-style loopback
    /// 10.0.2.2, kept for cross-platform QR payload compatibility) when explicitly allowed.
    static func validateControllerBaseUrl(_ rawUrl: String, allowLoopbackHttp: Bool = true) -> Result<String, Error> {
        var trimmed = rawUrl.trimmingCharacters(in: .whitespacesAndNewlines)
        while trimmed.hasSuffix("/") { trimmed.removeLast() }
        guard !trimmed.isEmpty else { return .failure(PairingUriError.malformed("empty controller URL")) }

        guard let components = URLComponents(string: trimmed) else {
            return .failure(PairingUriError.malformed(trimmed))
        }
        guard let scheme = components.scheme?.lowercased() else {
            return .failure(PairingUriError.unsupportedScheme(""))
        }
        guard let host = components.host?.lowercased() else {
            return .failure(PairingUriError.missingHost)
        }

        if scheme == "https" {
            return .success(trimmed)
        }
        if scheme == "http" {
            let isLoopback = host == "localhost" || host == "127.0.0.1" || host == "::1" || host == "10.0.2.2"
            if allowLoopbackHttp && isLoopback {
                return .success(trimmed)
            }
            return .failure(PairingUriError.insecureHttp(host))
        }
        return .failure(PairingUriError.unsupportedScheme(scheme))
    }
}

private extension String {
    var nilIfEmpty: String? { isEmpty ? nil : self }
}
